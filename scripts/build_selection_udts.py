#!/usr/bin/env python3
"""Generate the WF-GH glue UDTs from the helper scripts under `tools/`.

`hyphaeon_bundle` cannot be ported verbatim: its classic `<command>`
loops over `$el.element_identifier` to stage collection elements under
names the helper script looks up, and a job container never sees element
identifiers. The restructure (same as the inventory UDTs):
the IUC `collection_element_identifiers` tool emits the identifiers as
DATA, the collection itself renders as a JSON array of `{"path": ...}`
records, and a small staging program pairs paths with identifiers BY
POSITION -- with the count asserted before anything is staged, so a
mis-paired collection fails loudly instead of silently relabelling genes.

⛔ THE PYTHON IS NOT REWRITTEN HERE, IT IS INLINED VERBATIM from `tools/`;
the classic wrappers keep running it on a local Galaxy and the two copies
cannot drift. Only the ARGUMENT SHAPE changes: a `--staged` directory the
classic wrapper builds from identifiers becomes a directory the staging
program builds from rendered collection JSON + identifier files.

    python3 scripts/build_selection_udts.py           # write udt/
    python3 scripts/build_selection_udts.py --check   # non-zero if stale
"""

from __future__ import annotations

import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
UDT = ROOT / "udt"

#: Galaxy interpolates this ANYWHERE in a shell_command, heredocs included.
FORBIDDEN = "$("

HEADER = """# ⛔ GENERATED by scripts/build_selection_udts.py -- do not hand-edit.
# The Python below is inlined VERBATIM from the wrapper's helper under tools/; edit it there and
# regenerate. Only the argument shape differs from the classic tool: collection elements are staged
# from rendered collection JSON + element-identifier files (paired by position, count-asserted),
# because a job container receives paths and never sees a collection's identifiers.
"""


#: UDT-only glue with NO classic counterpart: builds the `staged/` directory
#: the classic wrapper creates by looping `$el.element_identifier`. Reads a
#: rendered collection JSON array ([{"path": ...}, ...]), an identifier file
#: (one element identifier per line), asserts the counts agree, then links
#: each path to {outdir}/{safe_name(id)}.{ext}. safe_name is imported from
#: the sibling inlined helper so the naming rule cannot drift between the
#: two files in one job directory.
STAGE_GLU = '''#!/usr/bin/env python3
"""Stage collection elements as {safe_name(id)}.{ext} symlinks (UDT glue)."""

import argparse
import importlib.util
import json
import os
import sys


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--helper", required=True,
                    help="Inlined helper module providing safe_name().")
    ap.add_argument("--map", action="append", required=True,
                    dest="maps", metavar="JSON:DIR:EXT:IDS",
                    help="rendered-collection-json : output dir : extension : identifiers file")
    args = ap.parse_args()

    spec = importlib.util.spec_from_file_location("helper", args.helper)
    helper = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(helper)
    safe_name = helper.safe_name

    for mapping in args.maps:
        json_path, out_dir, ext, ids_path = mapping.rsplit(":", 3)
        raw = open(json_path).read()
        recs = json.loads(raw[raw.index("["):raw.rindex("]") + 1])
        paths = [r["path"] for r in recs if isinstance(r, dict) and r.get("path")]
        with open(ids_path, encoding="utf-8-sig") as fh:
            ids = [ln.strip() for ln in fh if ln.strip()]
        if len(paths) != len(ids):
            sys.exit("ERROR: {} has {} element(s) but {} has {} identifier(s); "
                     "refusing to pair collection elements by position "
                     "(they would be silently mislabelled)".format(
                         json_path, len(paths), ids_path, len(ids)))
        if len(set(ids)) != len(ids):
            sys.exit("ERROR: duplicate element identifiers in " + ids_path)
        os.makedirs(out_dir, exist_ok=True)
        for ident, src in zip(ids, paths):
            dest = os.path.join(out_dir, safe_name(ident) + "." + ext)
            if os.path.exists(dest):
                os.remove(dest)
            os.symlink(os.path.abspath(src), dest)


if __name__ == "__main__":
    main()
'''


def read_helper(relpath: str) -> str:
    """A helper script from tools/, refused if it carries the sequence Galaxy would interpolate."""
    body = (ROOT / relpath).read_text(encoding="utf-8").rstrip("\n")
    if FORBIDDEN in body:
        sys.exit(f"REFUSING: {relpath} contains `{FORBIDDEN}`, which Galaxy would interpolate "
                 f"inside the heredoc, corrupting the inlined script.")
    return body


def _indent(script: str) -> str:
    return "\n".join(f"  {ln}" if ln else "" for ln in script.splitlines())


DISCOVER = """      - discover_via: pattern
        pattern: '(?:\\\\d+_)?(?P<designation>.+)\\\\.fasta'
        directory: prepared
        format: fasta
        visible: false
        recurse: false
        match_relative_path: false
        assign_primary_output: false
        sort_key: filename
        sort_comp: lexical"""


def render(tool_id: str, version: str, name: str, description: str,
           helper_path: str, shell: str, inputs: str, outputs: str,
           help_text: str) -> str:
    script = read_helper(helper_path)
    if FORBIDDEN in STAGE_GLU:
        sys.exit(f"REFUSING: STAGE_GLU contains `{FORBIDDEN}`")
    return HEADER + f"""class: GalaxyUserTool
id: {tool_id}
version: "{version}"
name: {name}
description: {description}
container: quay.io/biocontainers/python:3.12
shell_command: |
{shell.format(helper=_indent(script), stage=_indent(STAGE_GLU))}
{inputs}
{outputs}
help:
  format: markdown
  content: |
{_indent(_indent(help_text))}
"""


