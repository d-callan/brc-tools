def build() -> dict[str, str]:
    return {
        "hyphaeon_bundle.gxtool.yml": render(
            "brc-hyphaeon-bundle", "0.1.0",
            "HyphAeon bundle (BRC UDT)",
            "bundle per-orthogroup HyphAeon results into UCSC tracks + TACC bundle",
            "tools/hyphaeon_bundle/hyphaeon_bundle.py",
            BUNDLE_SHELL, BUNDLE_INPUTS, BUNDLE_OUTPUTS, BUNDLE_HELP),
    }


def _check_orphans(rendered: dict[str, str]) -> list[str]:
    stale = []
    for f in sorted(UDT.glob("*.gxtool.yml")):
        if f.name in rendered:
            continue
        if "build_selection_udts.py" in f.read_text(encoding="utf-8")[:400]:
            stale.append(f.name)
    return stale


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="compare against udt/ and exit non-zero if stale")
    args = ap.parse_args()

    rendered = build()
    orphans = _check_orphans(rendered)
    if orphans:
        sys.exit(f"REFUSING: UDT(s) carry this generator's header but are no "
                 f"longer produced: {orphans}")

    stale = []
    for filename, body in rendered.items():
        path = UDT / filename
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if args.check:
            if current != body:
                stale.append(filename)
            continue
        path.write_text(body, encoding="utf-8")
        print(f"  {'unchanged' if current == body else 'wrote':>9} udt/{filename}")

    if args.check:
        for filename in stale:
            print(f"  STALE udt/{filename}")
        if stale:
            print("  Regenerate with: python3 scripts/build_selection_udts.py")
            return 1
        print(f"  all committed selection UDTs match their helpers")
    return 0


if __name__ == "__main__":
    sys.exit(main())
